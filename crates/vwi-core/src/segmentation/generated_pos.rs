#[inline]
pub fn lookup_pos_tag(word: &str) -> Option<PosTag> {
    let lower = word.to_lowercase();
    POS_LEXICON
        .binary_search_by_key(&lower.as_str(), |&(k, _)| k)
        .ok()
        .map(|idx| POS_LEXICON[idx].1)
}
