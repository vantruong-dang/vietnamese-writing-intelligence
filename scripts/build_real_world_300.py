def build_300_benchmark() -> list[dict[str, object]]:
    """Tải 75 ca hiện có và kết hợp với 225 ca mới thành 300 ca hoàn chỉnh."""
    # 1. Tải 75 ca hiện có
    existing_cases: list[dict[str, object]] = []
    if DATA_FILE.exists():
        with open(DATA_FILE, encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if line:
                    c = json.loads(line)
                    if c.get("id") == "REAL_MT_002":
                        c["anchors_to_preserve"] = ["phần mềm"]
                    existing_cases.append(c)

    existing_ids = {c["id"] for c in existing_cases}
    print(f"Loaded {len(existing_cases)} existing cases.")

    # 2. Xây dựng 115 ca flawed mới
    new_flawed: list[dict[str, object]] = []
    for item in NEW_FLAWED_CASES:
        case = create_flawed_case(
            cid=item[0],
            source_type=item[1],
            input_text=item[2],
            rule_id=item[3],
            text_span=item[4],
            expected_rewrite=item[5],
            anchors_to_preserve=item[6],
            source_ref=item[7],
        )
        if case["id"] in existing_ids:
            raise ValueError(f"Duplicate ID: {case['id']}")
        new_flawed.append(case)

    # 3. Xây dựng 110 ca clean mới
    new_clean: list[dict[str, object]] = []
    for item in NEW_CLEAN_CASES:
        case = create_clean_case(
            cid=item[0],
            source_type=item[1],
            input_text=item[2],
            anchors_to_preserve=item[3],
            source_ref=item[4],
        )
        if case["id"] in existing_ids:
            raise ValueError(f"Duplicate ID: {case['id']}")
        new_clean.append(case)

    # 4. Gom nhóm: Flawed trước, Clean sau (hoặc giữ existing + new)
    all_flawed = [c for c in existing_cases if c["gold_spans"]] + new_flawed
    all_clean = [c for c in existing_cases if not c["gold_spans"]] + new_clean
    combined = all_flawed + all_clean

    # 5. Kiểm định tính toàn vẹn (Integrity Checks)
    assert len(all_flawed) == 150, f"Expected 150 flawed cases, got {len(all_flawed)}"
    assert len(all_clean) == 150, f"Expected 150 clean cases, got {len(all_clean)}"
    assert len(combined) == 300, f"Expected 300 cases, got {len(combined)}"

    seen_ids = set()
    for c in combined:
        cid = c["id"]
        assert cid not in seen_ids, f"Duplicate ID found: {cid}"
        seen_ids.add(cid)

        # Kiểm tra offset ký tự tuyệt đối
        for span in c["gold_spans"]:
            start = span["start"]
            end = span["end"]
            expected_text = span["text_span"]
            actual_text = c["input_text"][start:end]
            assert actual_text == expected_text, (
                f"Offset mismatch for {cid}: expected '{expected_text}', got '{actual_text}'"
            )

        # Kiểm tra anchors
        for anchor in c["anchors_to_preserve"]:
            assert anchor in c["input_text"], f"Anchor '{anchor}' not found in input_text of {cid}"

    return combined


def main() -> None:
    combined = build_300_benchmark()
    with open(DATA_FILE, "w", encoding="utf-8") as f:
        for c in combined:
            f.write(json.dumps(c, ensure_ascii=False) + "\n")
    print(f"Successfully generated and wrote {len(combined)} cases to {DATA_FILE}")


if __name__ == "__main__":
    main()
