def create_flawed_case(
    cid: str,
    source_type: str,
    input_text: str,
    rule_id: str,
    text_span: str,
    expected_rewrite: str,
    anchors_to_preserve: list[str],
    source_ref: str,
    expected_action: str = "review_comment",
) -> dict[str, object]:
    start = input_text.find(text_span)
    if start == -1:
        raise ValueError(f"Span '{text_span}' not found in '{input_text}' for {cid}")
    end = start + len(text_span)
    return {
        "id": cid,
        "source_type": source_type,
        "input_text": input_text,
        "expected_action": expected_action,
        "gold_spans": [
            {
                "rule_id": rule_id,
                "text_span": text_span,
                "start": start,
                "end": end,
            }
        ],
        "expected_rewrite": expected_rewrite,
        "anchors_to_preserve": anchors_to_preserve,
        "source_ref": source_ref,
    }


def create_clean_case(
    cid: str,
    source_type: str,
    input_text: str,
    anchors_to_preserve: list[str],
    source_ref: str,
) -> dict[str, object]:
    return {
        "id": cid,
        "source_type": source_type,
        "input_text": input_text,
        "expected_action": "no_change",
        "gold_spans": [],
        "expected_rewrite": "",
        "anchors_to_preserve": anchors_to_preserve,
        "source_ref": source_ref,
    }


